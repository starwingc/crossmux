inline Art forIcon(const UIIcon icon) {
  switch (icon) {
    case UIIcon::Transfer:
      return kTransfer;
    case UIIcon::WeRead:
      return kOpenBook;
    case UIIcon::Opds:
      return kHeartScroll;
    case UIIcon::AirPage:
      return kPlane;
    case UIIcon::ReadingStats:
      return kBars;
    case UIIcon::Sudoku:
      return kSudoku;
    case UIIcon::Gomoku:
      return kStones;
    case UIIcon::Sokoban:
      return kCrate;
    case UIIcon::ChineseChess:
      return kChessPiece;
    case UIIcon::Standby:
      return kMoon;
    case UIIcon::Buddy:
      return kCatFace;
    case UIIcon::Calculator:
      return kCalculator;
    case UIIcon::Minesweeper:
      return kMine;
    case UIIcon::Game2048:
      return k2048;
    case UIIcon::Avatar:
      return kAvatar;
    case UIIcon::Woodfish:
      return kWoodfish;
    case UIIcon::PixelSwitch:
      return kPixelCanvas;
    default:
      return nullptr;
  }
}

