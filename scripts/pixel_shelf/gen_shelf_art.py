#!/usr/bin/env python3
"""Cut the PixelLab no-cover card (book_card_nocover_96x128.png, 1-bit RGBA) into
the pieces the Pixel bookshelf draws at any card size, and write
src/components/themes/pixel/PixelShelfArt.h.

  corner  15x15 top-left corner (rivet + chamfer); mirrored for the other three
  edge    the 15 px border cross-section, read along the top edge
  wave    one period of the wavy divider
  book    the open book with its light rays

Cells: '#' ink, '.' paper, ' ' leave alone, 'c' paper only on a no-cover card
(where a cover is drawn the cover shows through).

Usage: python3 scripts/pixel_shelf/gen_shelf_art.py
"""
from pathlib import Path

from PIL import Image

HERE = Path(__file__).resolve().parent
OUT = HERE.parents[1] / "src/components/themes/pixel/PixelShelfArt.h"

CARD_X, CARD_Y = 9, 7  # top-left of the card body in the source image
CORNER = 15
BORDER = 9  # the frame's own width; content starts here on both axes
EDGE_X = 40  # a column of plain top edge
WAVE_Y, WAVE_X, WAVE_H = 49, 23, 3
BOOK = (32, 58, 33, 23)  # x, y, w, h


def cell(im, x, y):
    r, _, _, a = im.getpixel((x, y))
    if a == 0:
        return " "
    return "#" if r < 128 else "."


def main():
    im = Image.open(HERE / "book_card_nocover_96x128.png").convert("RGBA")

    corner = []
    for dy in range(CORNER):
        row = ""
        for dx in range(CORNER):
            c = cell(im, CARD_X + dx, CARD_Y + dy)
            if c == "." and dx >= BORDER and dy >= BORDER:
                c = "c"
            row += c
        corner.append(row)

    edge = "".join(cell(im, EDGE_X, CARD_Y + d) for d in range(CORNER))
    edge = edge[:BORDER] + edge[BORDER:].replace(".", "c")

    # The generated divider drifts between 6 and 7 px periods; keep its cleanest period.
    period = 6
    wave = ["".join(cell(im, x, WAVE_Y + r) for x in range(WAVE_X, WAVE_X + period)) for r in range(WAVE_H)]

    bx, by, bw, bh = BOOK
    book = ["".join(cell(im, bx + x, by + y) for x in range(bw)) for y in range(bh)]

    def arr(name, rows):
        body = ",\n".join(f'    "{r}"' for r in rows)
        return f"inline constexpr const char* {name}[] = {{\n{body}}};\n"

    OUT.write_text(
        "#pragma once\n\n"
        "// Generated by scripts/pixel_shelf/gen_shelf_art.py from book_card_nocover_96x128.png\n"
        "// (PixelLab). Cells: '#' ink, '.' paper, ' ' untouched, 'c' paper on a no-cover card only.\n"
        "namespace PixelShelfArt {\n\n"
        f"constexpr int kCorner = {CORNER};\n"
        f"constexpr int kBorder = {BORDER};\n"
        f"constexpr int kWaveW = {period};\n"
        f"constexpr int kWaveH = {WAVE_H};\n"
        f"constexpr int kBookW = {bw};\n"
        f"constexpr int kBookH = {bh};\n\n"
        + arr("kCornerArt", corner)
        + f'inline constexpr const char* kEdgeArt = "{edge}";\n'
        + arr("kWaveArt", wave)
        + arr("kBookArt", book)
        + "\n}  // namespace PixelShelfArt\n"
    )
    print(OUT)
    print("\n".join(corner))
    print(edge)
    print("\n".join(wave))
    print("\n".join(book))


if __name__ == "__main__":
    main()
