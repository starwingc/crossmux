#!/usr/bin/env python3
"""Rasterize the Pixel-theme study room into src/components/themes/pixel/PixelRoomArt.h.

    python3 scripts/pixel_room/gen_room.py

room.rle is a 160x256 grayscale drawing quantized to five levels, one row per '|'-separated
field of char+count runs: '#' <48, '%' <96, '+' <144, '-' <200, '.' paper (luminance).
It is reduced to 1-bit for e-ink: '#' ink, '%' 50% checker, '+' 25% dots, '-' '.' paper.
The header stores one bit per cell, MSB first, 20 bytes per row (1 = ink).
"""
import os
import re

HERE = os.path.dirname(__file__)
ROOT = os.path.join(HERE, '..', '..')
OUT = os.path.join(ROOT, 'src', 'components', 'themes', 'pixel', 'PixelRoomArt.h')


CLOCK_X, CLOCK_Y, CLOCK_CLEAR_R = 76, 22, 7.2  # art cells; keep in sync with PixelRoom.cpp


def ink(ch, x, y):
    if ch == '#':
        return 1
    if ch == '%':
        return int((x + y) % 2 == 0)
    if ch == '+':
        return int(x % 2 == 0 and y % 2 == 0)
    return 0


def main():
    text = open(os.path.join(HERE, 'room.rle')).read().strip()
    grid = [''.join(c * int(n) for c, n in re.findall(r'(\D)(\d+)', r)) for r in text.split('|')]
    H, W = len(grid), len(grid[0])
    # The wall clock's hands are drawn live by PixelRoom (drawClockHands): blank the face
    # inside the hour ticks so only the drawn hands show.
    grid = [''.join('.' if (x - CLOCK_X) ** 2 + (y - CLOCK_Y) ** 2 <= CLOCK_CLEAR_R ** 2 else c
                    for x, c in enumerate(row)) for y, row in enumerate(grid)]
    assert W % 8 == 0 and all(len(r) == W for r in grid)
    rows = []
    for y, row in enumerate(grid):
        b = bytearray()
        for i in range(0, W, 8):
            v = 0
            for j in range(8):
                v = (v << 1) | ink(row[i + j], i + j, y)
            b.append(v)
        rows.append(', '.join(f'0x{v:02X}' for v in b))
    body = ',\n  '.join(rows)
    with open(OUT, 'w') as f:
        f.write('#pragma once\n// Generated by scripts/pixel_room/gen_room.py — do not edit.\n'
                '#include <cstdint>\n\nnamespace PixelRoomArt {\n'
                f'constexpr int kCols = {W};\nconstexpr int kRows = {H};\nconstexpr int kRowBytes = {W // 8};\n'
                f'inline constexpr uint8_t kRoom[kRows * kRowBytes] = {{\n  {body}\n}};\n'
                '}  // namespace PixelRoomArt\n')
    print('wrote', os.path.relpath(OUT, ROOT))


if __name__ == '__main__':
    main()
