#!/usr/bin/env python3
"""Rasterize the Pixel-theme study room into src/components/themes/pixel/PixelRoomArt.h.

    python3 scripts/pixel_room/gen_room.py

room_art.PATHS holds rectangle-only SVG path data ("M x y h w v h h -w z" runs) on a
120x200 grid; later entries paint over earlier ones. The header stores one bit per cell,
MSB first, 15 bytes per row (1 = ink).
"""
import os
import re
import sys

sys.path.insert(0, os.path.dirname(__file__))
from room_art import PATHS  # noqa: E402

W, H = 120, 200
ROOT = os.path.join(os.path.dirname(__file__), '..', '..')
OUT = os.path.join(ROOT, 'src', 'components', 'themes', 'pixel', 'PixelRoomArt.h')


def rects(d):
    # Each subpath: M x y h w v h h -w z  (also accepts the "...H x z" form)
    for m in re.finditer(r'M(-?\d+) (-?\d+)h(-?\d+)v(-?\d+)', d):
        x, y, w, h = map(int, m.groups())
        yield x, y, w, h


def main():
    grid = [[0] * W for _ in range(H)]
    for d, ink in PATHS:
        for x, y, w, h in rects(d):
            for yy in range(max(0, y), min(H, y + h)):
                for xx in range(max(0, x), min(W, x + w)):
                    grid[yy][xx] = 1 if ink else 0
    rows = []
    for row in grid:
        b = bytearray()
        for i in range(0, W, 8):
            v = 0
            for j in range(8):
                v = (v << 1) | row[i + j]
            b.append(v)
        rows.append(', '.join(f'0x{v:02X}' for v in b))
    body = ',\n  '.join(rows)
    with open(OUT, 'w') as f:
        f.write('#pragma once\n// Generated by scripts/pixel_room/gen_room.py — do not edit.\n'
                '#include <cstdint>\n\nnamespace PixelRoomArt {\n'
                f'constexpr int kCols = {W};\nconstexpr int kRows = {H};\nconstexpr int kRowBytes = {W // 8};\n'
                f'inline constexpr uint8_t kRoom[kRows * kRowBytes] = {{\n  {body}\n}};\n'
                '}  // namespace PixelRoomArt\n')
    print('wrote', os.path.relpath(OUT, ROOT))


if __name__ == '__main__':
    main()
